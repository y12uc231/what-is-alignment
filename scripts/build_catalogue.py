"""Build docs/catalogue.md and data/cases_final.yaml from case cards plus the writers' verdict files.

Each case card (data/cases/*.yaml) gets the final verdict from data/verdicts/*.yaml. Cards listed as duplicates of
another card are folded into it. Fails if any card has no verdict.

Usage: python -I scripts/build_catalogue.py
"""
import glob
import json
import sys
from collections import defaultdict
from pathlib import Path

import yaml

ORDER = ["alignment", "misaligned-objective", "boundary", "model-organism", "not-alignment"]
TITLES = {
    "alignment": "Alignment failures",
    "misaligned-objective": "Misaligned objectives (optimizers with no goals of their own)",
    "boundary": "Boundary cases",
    "model-organism": "Model organisms (built by researchers to study misalignment)",
    "not-alignment": "Not alignment failures",
}
DOC = {"alignment": "05-cases-alignment.md", "misaligned-objective": "05-cases-alignment.md",
       "boundary": "07-boundary-cases.md", "model-organism": "06-cases-not-alignment.md",
       "not-alignment": "06-cases-not-alignment.md"}


def link(src, papers):
    p = papers.get(src, {})
    url = p.get("url") or (f"https://arxiv.org/abs/{src}" if p.get("kind") == "arxiv" else "")
    label = src if p.get("kind") == "arxiv" else (p.get("org") or src)
    return f"[{label}]({url})" if url else src


def cell(s):
    return " ".join(str(s).split()).replace("|", "/")


def main():
    papers = {}
    for line in Path("data/papers.jsonl").read_text().splitlines():
        if line.strip():
            d = json.loads(line)
            papers[d["id"]] = d
    cards = {}
    for f in sorted(glob.glob("data/cases/*.yaml")):
        for c in yaml.safe_load(open(f)) or []:
            cards[c["id"]] = c
    verdicts = {}
    for f in sorted(glob.glob("data/verdicts/*.yaml")):
        for v in yaml.safe_load(open(f)) or []:
            verdicts[v["case"]] = v
    dup_of = {}
    for cid, v in verdicts.items():
        for d in v.get("duplicates") or []:
            if d in cards and d != cid and d not in dup_of and cid not in dup_of:
                dup_of[d] = cid
    missing = [c for c in cards if c not in verdicts and c not in dup_of]
    if missing:
        print(f"FAIL: {len(missing)} cards have no verdict, e.g. {missing[:5]}")
        return 1
    groups = defaultdict(list)
    final = []
    for cid, c in cards.items():
        if cid in dup_of:
            continue
        v = verdicts[cid]
        srcs = list(dict.fromkeys([*(c.get("sources") or [])] +
                                  [s for d, t in dup_of.items() if t == cid for s in cards[d].get("sources") or []]))
        row = {"id": cid, "title": c["title"], "year": c.get("year"), "system": c.get("system"),
               "setting": c.get("setting"), "verdict": v["verdict"], "relative_to": v.get("relative_to"),
               "family": v.get("family"), "label": v.get("label"), "one_line": v.get("one_line"),
               "sources": srcs, "duplicates": [d for d, t in dup_of.items() if t == cid],
               "reader_candidate": c.get("candidate_verdict")}
        groups[v["verdict"]].append(row)
        final.append(row)
    Path("data/cases_final.yaml").write_text(yaml.safe_dump(final, sort_keys=False, allow_unicode=True, width=120))
    out = ["# Catalogue of cases", "",
           f"This table lists all {len(final)} documented cases in the repository with their verdicts under the rules of "
           "[Section 1](01-first-principles.md). It is generated by `scripts/build_catalogue.py` from the case cards in "
           "`data/cases/` (each with verbatim, checked quotes from its sources) and the verdicts in `data/verdicts/`; "
           "`data/cases_final.yaml` has the same content in machine-readable form. Verdicts are stated relative to "
           "a principal. Cases that several sources describe appear once, with all sources listed.", ""]
    counts = ", ".join(f"{len(groups[k])} {TITLES[k].lower()}" for k in ORDER if groups[k])
    out += [f"Counts: {counts}.", ""]
    for k in ORDER:
        rows = sorted(groups[k], key=lambda r: (str(r["family"]), r["year"] or 0, r["title"]))
        if not rows:
            continue
        out += [f"## {TITLES[k]} ({len(rows)})", "", f"The documents discuss most of these cases in prose, mainly in [{DOC[k]}]({DOC[k]}) and [07-boundary-cases.md](07-boundary-cases.md); this table is the complete list.", "",
                "| Year | Case | Relative to | Family | Why | Sources |", "|---|---|---|---|---|---|"]
        for r in rows:
            out.append(f"| {r['year']} | {cell(r['title'])} | {cell(r['relative_to'])} | {cell(r['family'])} | "
                       f"{cell(r['one_line'])} | {', '.join(link(s, papers) for s in r['sources'])} |")
        out.append("")
    Path("docs/catalogue.md").write_text("\n".join(out))
    print(f"catalogue: {len(final)} cases ({len(dup_of)} duplicate cards folded); " +
          ", ".join(f"{k}={len(groups[k])}" for k in ORDER))
    return 0


if __name__ == "__main__":
    sys.exit(main())
